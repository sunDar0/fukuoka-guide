    function generateGuide(startDate, endDate, nights, adults, children, infants, mode) {
        // 일정은 이동 수단별 2~5박만 있다. 6~7박은 5박 일정을 보여주고 남는 날은 자유 일정으로 안내한다.
        var modeTemplates = window.itineraryTemplates[mode] || window.itineraryTemplates.transit;
        var template = modeTemplates[nights];
        if (!template) {
            // Fallback: use closest available
            var keys = Object.keys(modeTemplates).map(Number).sort(function (a, b) { return a - b; });
            var closest = keys.reduce(function (prev, curr) {
                return Math.abs(curr - nights) < Math.abs(prev - nights) ? curr : prev;
            });
            template = modeTemplates[closest];
        }

        renderOverview(startDate, endDate, nights, adults, children, infants, mode);
        renderInfoCards(startDate);
        renderItinerary(startDate, template, nights);
        renderBudget(nights, adults, children, infants, template.rentalDays || 0);
        renderAttractions();
        renderFoodGuide();
        renderTransportGuide(nights, mode);
        renderAccommodationGuide();
        setupSectionNav();
    }

