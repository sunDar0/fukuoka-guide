    function renderItinerary(startDate, template, nights) {
        var navContainer = document.getElementById('day-nav');
        var contentContainer = document.getElementById('itinerary-content');

        navContainer.innerHTML = '';
        contentContainer.innerHTML = '';

        // 6~7박은 5박 일정의 마지막 날(귀국일)을 실제 귀국일로 옮기고, 그 앞의 남는 날을 자유 일정으로 둔다.
        var extraDays = Math.max(0, nights - template.nights);
        var lastIndex = template.days.length - 1;
        if (extraDays > 0) {
            var freeStart = new Date(startDate);
            freeStart.setDate(freeStart.getDate() + template.nights);
            var freeEnd = new Date(startDate);
            freeEnd.setDate(freeEnd.getDate() + nights - 1);
            contentContainer.innerHTML =
                '<div class="transport-tip" style="margin-bottom: 1.5rem;">💡 ' + nights + '박 여행은 ' + template.nights + '박 일정 기준이에요. ' +
                (freeStart.getMonth() + 1) + '/' + freeStart.getDate() +
                (extraDays > 1 ? '~' + (freeEnd.getMonth() + 1) + '/' + freeEnd.getDate() : '') +
                '(' + extraDays + '일)은 자유 일정으로 비워 두었고, 마지막 날 일정은 귀국일에 맞췄어요.</div>';
        }

        template.days.forEach(function (dayData, i) {
            var dayOffset = (extraDays > 0 && i === lastIndex) ? nights : i;
            var currentDate = new Date(startDate);
            currentDate.setDate(currentDate.getDate() + dayOffset);
            var dateStr = (currentDate.getMonth() + 1) + '/' + currentDate.getDate() + ' (' + dayNames[currentDate.getDay()] + ')';

            // Nav button
            var btn = document.createElement('button');
            btn.className = 'day-nav-btn' + (i === 0 ? ' active' : '');
            btn.setAttribute('data-day', i + 1);
            btn.textContent = (dayOffset + 1) + '일차';
            btn.addEventListener('click', function () {
                navContainer.querySelectorAll('.day-nav-btn').forEach(function (b) {
                    b.classList.remove('active');
                });
                btn.classList.add('active');
                var target = document.getElementById('day-' + (i + 1));
                if (target) {
                    target.scrollIntoView({ behavior: 'smooth', block: 'start' });
                }
            });
            navContainer.appendChild(btn);

            // Day card with timeline
            var timelineHtml = '';
            var dayMonth = currentDate.getMonth() + 1;
            dayData.timeline.forEach(function (base) {
                // season: 그 일차의 실제 날짜 월이 months 에 들면 항목 내용을 계절 내용으로 바꾼다 (time 은 유지)
                var item = base;
                var se = base.season;
                if (se && se.months && se.months.indexOf(dayMonth) >= 0) {
                    item = {
                        time: base.time,
                        icon: se.icon !== undefined ? se.icon : base.icon,
                        activity: se.activity !== undefined ? se.activity : base.activity,
                        details: se.details !== undefined ? se.details : base.details,
                        childNote: se.childNote !== undefined ? se.childNote : base.childNote
                    };
                }
                var childNoteHtml = '';
                // childNote 에는 아이·노부모 동반 안내가 섞여 있어 인원 구성과 관계없이 보여준다.
                if (item.childNote && item.childNote.trim() !== '') {
                    childNoteHtml =
                        '<div class="child-note">' +
                            '<span class="child-note-icon">👨‍👩‍👧</span> ' + item.childNote +
                        '</div>';
                }

                timelineHtml +=
                    '<div class="timeline-item">' +
                        '<div class="timeline-dot"></div>' +
                        '<span class="timeline-time">' + item.time + '</span>' +
                        '<div class="timeline-content">' +
                            '<p class="timeline-title">' + item.icon + ' ' + item.activity + '</p>' +
                            '<p class="timeline-description">' + item.details + '</p>' +
                            childNoteHtml +
                        '</div>' +
                    '</div>';
            });

            var dayEl = document.createElement('div');
            dayEl.id = 'day-' + (i + 1);
            dayEl.className = 'day-anchor';
            dayEl.style.marginBottom = '2rem';
            dayEl.innerHTML =
                '<div class="day-card">' +
                    '<div class="day-title">' + (dayOffset + 1) + '일차: ' + dayData.title + '</div>' +
                    '<p style="color: var(--text-muted); margin-bottom: 0.5rem; font-size: 0.9rem;">' + dateStr + '</p>' +
                    '<p style="color: var(--text-secondary); margin-bottom: 1.5rem;">' + dayData.summary + '</p>' +
                    '<div class="timeline-container">' +
                        timelineHtml +
                    '</div>' +
                '</div>';
            contentContainer.appendChild(dayEl);
        });
    }

